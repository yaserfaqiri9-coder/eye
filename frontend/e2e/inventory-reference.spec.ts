import { expect, test } from '@playwright/test'
import { setup } from './inventory-reference-fixture.mjs'

test.use({ channel: 'chromium', viewport: { width: 1440, height: 1000 } })

test('reference inventory list uses real quantities, all catalogue pages, filters, pagination and edit controls', async ({ page }) => {
  const problems = await setup(page)
  await page.goto('/inventory', { waitUntil: 'domcontentloaded' })
  const table = page.locator('.inventory-table')
  await expect(table.getByRole('row')).toHaveCount(9)
  await expect(table.getByRole('columnheader')).toHaveCount(6)
  await expect(table.getByRole('columnheader', { name: /SKU|کد جنس/ })).toHaveCount(0)
  const firstRow = table.locator('tbody tr').first()
  await expect(firstRow.locator('td').first().locator('summary')).toHaveCount(0)
  await expect(firstRow.locator('td').last().locator('summary')).toHaveAttribute('aria-label', 'عملیات Vigamox')
  const listBox = await page.locator('.inventory-list').boundingBox()
  const tabsBox = await page.getByRole('tablist', { name: 'بخش‌های گدام' }).boundingBox()
  const createBox = await page.getByRole('button', { name: 'ثبت محصول', exact: true }).boundingBox()
  const purchaseBox = await page.getByRole('link', { name: 'ثبت خرید', exact: true }).boundingBox()
  expect(tabsBox!.y).toBeLessThan(listBox!.y)
  expect(createBox!.y).toBeLessThan(listBox!.y)
  expect(purchaseBox!.y).toBeLessThan(listBox!.y)
  expect(await page.locator('.sidebar').evaluate(el => getComputedStyle(el).backgroundImage)).toContain('rgb(8, 155, 171)')
  expect(await firstRow.locator('.inventory-number').evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBe(16)
  expect(await firstRow.locator('.inventory-item__icon').evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBe(26)
  await expect(table.getByText('320', { exact: true })).toBeVisible()
  await expect(table.getByText('موجودی کم', { exact: true })).toHaveCount(2)
  await expect(table.getByText('ناموجود', { exact: true })).toHaveCount(1)
  await expect(page.locator('.inventory-list__count')).toHaveText('108 جنس')
  await page.screenshot({ path: '../docs/inventory-reference/desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'صفحه بعدی', exact: true }).click()
  await expect(table.getByText('1,234.125', { exact: true })).toBeVisible()
  await page.getByRole('searchbox', { name: 'جستجوی نام یا کد جنس' }).fill('DR-108')
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(table.getByText('جنس آزمایشی 108', { exact: true })).toBeVisible()
  await expect(table.getByRole('link', { name: 'دواخانه', exact: true })).toBeVisible()
  await page.getByRole('searchbox').fill('')
  await page.getByRole('button', { name: 'فیلتر موجودی' }).click()
  await page.getByRole('combobox', { name: 'فیلتر وضعیت', exact: true }).selectOption('out')
  await expect(table.getByRole('row')).toHaveCount(2)
  await expect(table.getByText('پماد چشمی', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'پاک‌کردن فیلترها' }).click()
  await page.getByRole('combobox', { name: 'فیلتر محل', exact: true }).selectOption('pharmacy')
  await expect(table.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: 'پاک‌کردن فیلترها' }).click()
  await page.getByRole('button', { name: 'فیلتر موجودی' }).click()
  await firstRow.locator('summary').click()
  await firstRow.getByRole('button', { name: 'ویرایش جنس', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('کد', { exact: true })).toHaveValue('DR-001')
  await page.getByRole('button', { name: 'انصراف', exact: true }).click()
  expect(problems).toEqual([])
})

test('the inventory list stays within a mobile viewport and empty searches are explicit', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const problems = await setup(page)
  await page.goto('/inventory', { waitUntil: 'domcontentloaded' })
  await expect(page.locator('.inventory-table').getByText('Vigamox', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../docs/inventory-reference/mobile.png', fullPage: true })
  const widths = await page.evaluate(() => ({ actual: document.documentElement.scrollWidth, viewport: innerWidth }))
  expect(widths.actual).toBeLessThanOrEqual(widths.viewport)
  await page.getByRole('searchbox', { name: 'جستجوی نام یا کد جنس' }).fill('does-not-exist')
  await expect(page.getByText('هیچ جنسی با این جستجو و فیلترها پیدا نشد.')).toBeVisible()
  expect(problems).toEqual([])
})

